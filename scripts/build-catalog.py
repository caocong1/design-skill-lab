#!/usr/bin/env python3
"""Build every catalogue view from the hand-curated source of truth.

Inputs
  catalog/resources.jsonl             hand-curated rows (schema v2); the only file humans edit
  catalog/taxonomy.json               domains, sections and kinds with zh + en titles and notes
  catalog/observed.jsonl              machine observations written by scripts/check-links.py
                                      (append-only; the latest record per id wins)
  docs/assets/thumbs/manifest.json    thumbnail manifest written by scripts/shoot-catalog.mjs (optional)

Outputs (generated; never edit by hand)
  skills/design-studio/references/catalog/catalog.jsonl   compact projection read by scripts/catalog.py
  skills/design-studio/references/catalog/taxonomy.json   domains and sections with counts, for catalog.py
  skills/design-studio/references/catalog/<domain>.md     one readable table view per domain
  skills/design-studio/references/catalog/README.md       how to query, column legend, domain list
  docs/data/catalog.json, docs/data/catalog.js            site data (catalog.js sets window.CATALOG_V2)
  docs/data/thumbs.js                                     window.THUMBS: ids with a QA-passed thumbnail
  docs/data/lab-catalog.js                                legacy window.CATALOG + window.CATALOG_ZH for docs/lab/
  docs/data/llms.txt                                      plain-text catalogue for agents
  docs/index.html, docs/catalog/index.html                the <!-- gen:* --> regions only (scripts/site_pages.py)

Usage
  scripts/build-catalog.py            validate, then write every output
  scripts/build-catalog.py --check    exit 1 if the catalogue is invalid or any generated file is stale
"""
