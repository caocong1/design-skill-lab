#!/usr/bin/env python3
"""Query the design resource catalogue that ships with this skill. Python 3 stdlib only; any working directory.

  catalog.py find <keywords...> [--domain D] [--section S] [--kind K] [--tier S,A] [--region cn]
                                [--reach static,js] [--free] [--limit 10] [--json]
  catalog.py show <id>              every field of one resource
  catalog.py route "<question>"     the best domains/sections for a need, with their top resources
  catalog.py recipes [domain]       machine endpoints (APIs, raw-SVG CDNs, mirrors) with a sample request
  catalog.py domains                domains and sections with counts

Keywords may be English or Chinese (Chinese is matched by known words and character pairs).
Ranking: keyword score (name > tags > Chinese text, best_for > section title, how_to_use > host; rarer words
count more; a row matching a word and its synonym, e.g. 配色 in the Chinese text and "palette" in the English,
counts more than one matching either), then tier, then reach (static before js, unknown, blocked), so what a
plain fetch can use comes first. Scores within the same quarter of the best score count as equally relevant
(keyword scores are too coarse to rank closer than that), so tier and reach decide among them.
Data: ../references/catalog/catalog.jsonl and taxonomy.json, generated by the Design Skill Lab.
"""
import argparse
import difflib
import json
import math
import pathlib
import re
import sys

DATA = pathlib.Path(__file__).resolve().parent.parent / 'references' / 'catalog'
TIER_RANK = {'S': 0, 'A': 1, 'B': 2}
REACH = ('static', 'js', 'unknown', 'blocked')
WEIGHTS = {'name': 6, 'tags': 4, 'zh': 3, 'best_for': 3, 'home': 1.5, 'how_to_use': 1.5, 'host': 1}
ZH_WEIGHT_FOR_CHINESE = 4       # a Chinese word can only match the Chinese text, so a hit there says a bit more
SYNONYM_WEIGHT = 0.6
